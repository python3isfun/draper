"""Design sheets: standalone cast, set and prop descriptions for downstream designers.

Each sheet is its own document with its own versioned JSON schema (served at
/v1/schemas/<sheet>.json) and is generated by its own model call. The story bible keeps the
story-facing side of the same entities (IDs, names, goals, relationships, arcs); the
sheets hold how they look. Entries are keyed by the story bible's IDs: every character,
look, location, location state, prop and prop state has exactly one sheet entry.

These are text descriptions to design from, never generated images.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

CAST_SHEET_SCHEMA_VERSION = "1.0"
SET_SHEET_SCHEMA_VERSION = "1.0"
PROP_SHEET_SCHEMA_VERSION = "1.0"

_MUST_KEEP = "Visual traits the story depends on; a designer must not change these."
_FREEDOM = "Aspects the designer may decide freely."
_CHANGES = "What differs from the base design, and nothing else."


# ---------------------------------------------------------------------------
# Cast


class CastMember(BaseModel):
    character_id: str
    name: str = Field("", description="Filled from the story bible; leave empty.")
    on_screen: bool = Field(
        True, description="False for characters only heard (phone, voice-over)."
    )
    age_range: str = Field(description="Apparent age, e.g. about 28.")
    gender_presentation: str
    build_and_height: str
    face: str = Field(description="Face shape, features and default expression.")
    hair: str
    distinguishing_features: str = Field(
        "", description="Scars, tattoos, glasses, anything that identifies the character."
    )
    default_wardrobe: str = Field(description="The base outfit, with fabrics and fit.")
    wardrobe_palette: str = Field(description="The character's color palette.")
    posture_and_mannerisms: str
    voice: str = Field(description="Timbre, pace and accent, for casting and dubbing.")
    must_keep: list[str] = Field(default_factory=list, description=_MUST_KEEP)
    design_freedom: list[str] = Field(default_factory=list, description=_FREEDOM)


class CastLook(BaseModel):
    """One registered look (look_id) of a character."""

    look_id: str
    character_id: str
    wardrobe: str
    hair_and_makeup: str
    condition: str = Field("", description="Physical state, e.g. soaked by rain, injured.")
    changes_from_base: str = Field(description=_CHANGES)
    must_keep: list[str] = Field(default_factory=list, description=_MUST_KEEP)


class CastSheet(BaseModel):
    schema_version: Literal["1.0"] = CAST_SHEET_SCHEMA_VERSION
    characters: list[CastMember]
    looks: list[CastLook] = Field(default_factory=list)

    def entries(self) -> dict[str, CastMember | CastLook]:
        """Entries keyed by the story-bible ID they describe (first one wins)."""
        out: dict[str, CastMember | CastLook] = {}
        for c in self.characters:
            out.setdefault(c.character_id, c)
        for lk in self.looks:
            out.setdefault(lk.look_id, lk)
        return out


# ---------------------------------------------------------------------------
# Sets


class SetLocation(BaseModel):
    location_id: str
    name: str = Field("", description="Filled from the story bible; leave empty.")
    interior_exterior: Literal["INT", "EXT", "INT/EXT"]
    era_and_region: str
    layout: str = Field(description="Shape, size and where things are, so blocking works.")
    key_furnishings: str
    materials_and_textures: str
    color_palette: str
    lighting: str = Field(description="Light sources and their direction and quality.")
    entrances_and_blocking: str = Field(
        description="Doors and windows, and how characters enter, exit and move."
    )
    ambient_sound: str = ""
    must_keep: list[str] = Field(default_factory=list, description=_MUST_KEEP)
    design_freedom: list[str] = Field(default_factory=list, description=_FREEDOM)


class SetState(BaseModel):
    """One registered state (location_state_id) of a location."""

    location_state_id: str
    location_id: str
    time_of_day: str
    lighting: str
    dressing_changes: str = Field("", description="Set dressing added, moved or removed.")
    condition: str = Field("", description="E.g. ransacked, flooded, decorated for a party.")
    changes_from_base: str = Field(description=_CHANGES)
    must_keep: list[str] = Field(default_factory=list, description=_MUST_KEEP)


class SetSheet(BaseModel):
    schema_version: Literal["1.0"] = SET_SHEET_SCHEMA_VERSION
    locations: list[SetLocation]
    states: list[SetState] = Field(default_factory=list)

    def entries(self) -> dict[str, SetLocation | SetState]:
        """Entries keyed by the story-bible ID they describe (first one wins)."""
        out: dict[str, SetLocation | SetState] = {}
        for loc in self.locations:
            out.setdefault(loc.location_id, loc)
        for st in self.states:
            out.setdefault(st.location_state_id, st)
        return out


# ---------------------------------------------------------------------------
# Props


class PropItem(BaseModel):
    prop_id: str
    name: str = Field("", description="Filled from the story bible; leave empty.")
    size_and_scale: str
    materials: str
    color_and_finish: str
    condition_and_wear: str
    distinguishing_marks: str = Field(
        "", description="What makes this exact object recognizable on screen."
    )
    handling: str = Field(description="Who handles it and how; how it reads in close-up.")
    must_keep: list[str] = Field(default_factory=list, description=_MUST_KEEP)
    design_freedom: list[str] = Field(default_factory=list, description=_FREEDOM)


class PropVariant(BaseModel):
    """One registered state (prop_state_id) of a prop."""

    prop_state_id: str
    prop_id: str
    condition: str
    changes_from_base: str = Field(description=_CHANGES)
    must_keep: list[str] = Field(default_factory=list, description=_MUST_KEEP)


class PropSheet(BaseModel):
    schema_version: Literal["1.0"] = PROP_SHEET_SCHEMA_VERSION
    props: list[PropItem] = Field(default_factory=list)
    states: list[PropVariant] = Field(default_factory=list)

    def entries(self) -> dict[str, PropItem | PropVariant]:
        """Entries keyed by the story-bible ID they describe (first one wins)."""
        out: dict[str, PropItem | PropVariant] = {}
        for p in self.props:
            out.setdefault(p.prop_id, p)
        for st in self.states:
            out.setdefault(st.prop_state_id, st)
        return out


SHEET_SCHEMAS: dict[str, type[BaseModel]] = {
    "cast-sheet": CastSheet,
    "set-sheet": SetSheet,
    "prop-sheet": PropSheet,
}
